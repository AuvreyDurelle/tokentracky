//! Price ceilings for the hosted cost check: no tier costs more than an id's ceiling, and
//! `packages/cloud/src/generated` is written from the bundled table; `TOKENTRACKY_CEILINGS_OUT` overrides the directory.
use std::{env, fs, path::PathBuf};
use tokentracky_core::{TokenCounts, ToolId};
use tokentracky_pricing::{Ceiling, bundled_table};

const HEADER: &str = "// Generated by crates/pricing. Do not edit.\n// Regenerate with `cargo test -p tokentracky-pricing`; CI checks it with scripts/check-generated-types.sh.\n";

/// Token mixes that reach every tier: short and long context, cache-heavy and one-hour cache writes.
fn mixes() -> Vec<TokenCounts> {
    let mix = |input, output, cache_read, cache_write, cache_write_1h| TokenCounts {
        input,
        output,
        cache_read,
        cache_write,
        reasoning: None,
        cache_write_1h,
    };
    vec![
        mix(1, 0, 0, 0, None),
        mix(1_000, 200, 0, 0, None),
        mix(300_000, 5_000, 0, 0, None),
        mix(2_000, 500, 900_000, 50_000, None),
        mix(250_000, 4_000, 0, 40_000, Some(40_000)),
        mix(3, 7, 11, 13, Some(5)),
    ]
}

/// The most `tokens` can cost under `ceiling`, rounded half up as the table rounds.
fn bound(tokens: &TokenCounts, ceiling: Ceiling) -> u64 {
    let counts = [tokens.input, tokens.output, tokens.cache_read, tokens.cache_write];
    let picodollars: u128 = counts
        .iter()
        .zip(ceiling)
        .filter(|(count, _)| **count > 0)
        .map(|(&count, rate)| u128::from(count) * u128::from(rate.expect("a priced kind has a ceiling")))
        .sum();
    u64::try_from((picodollars + 500_000) / 1_000_000).unwrap()
}

/// The dearest cost the table gives `tokens`, Standard or Fast.
fn dearest(model: &str, tool: ToolId, tokens: &TokenCounts) -> Option<u64> {
    [false, true]
        .into_iter()
        .filter_map(|priority| bundled_table().price_tier(tokens, model, tool, priority))
        .map(|priced| priced.cost_microusd)
        .max()
}

#[test]
fn no_tier_costs_more_than_the_ceiling() {
    let table = bundled_table();
    let ceilings = table.ceilings();
    assert!(ceilings.len() > 1_000);
    for (id, ceiling) in ceilings {
        assert_eq!(table.ceiling(id, ToolId::Claude), Some(ceiling), "{id}");
        for tokens in mixes() {
            if let Some(cost) = dearest(id, ToolId::Claude, &tokens) {
                assert!(cost <= bound(&tokens, ceiling), "{id} {tokens:?}: {cost}");
            }
        }
    }
}

