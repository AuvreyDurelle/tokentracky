fn json<T: serde::Serialize + ?Sized>(value: &T) -> String {
    serde_json::to_string(value).unwrap()
}

#[test]
fn generates_typescript_ceilings() {
    let table = bundled_table();
    let mut out = format!(
        "{HEADER}\n/** Picodollars per token for input, output, cache read and cache write: the most one token of each kind can cost under a model. `null` where it has no rate for that kind. */\nexport type Ceiling = readonly [number | null, number | null, number | null, number | null];\n/** Every id the bundled price table answers for without normalizing, with its ceiling. Table {}. */\nexport const PRICE_CEILINGS: ReadonlyMap<string, Ceiling> = new Map<string, Ceiling>([\n",
        table.version()
    );
    for (id, ceiling) in table.ceilings() {
        out += &format!("  [{}, {}],\n", json(id), json(&ceiling));
    }
    out += "]);\n";

    let mut cases = format!(
        "{HEADER}\nimport type {{ ToolId }} from '@tokentracky/core';\nimport type {{ Ceiling }} from './price-ceilings.ts';\n\n/** For `cost-ceiling.test.ts`: a logged id and tool, the ceiling the Rust table finds, and costs it gives token mixes (input, output, cache read, cache write, cost) on their dearest tier. */\nexport const CEILING_CASES: ReadonlyArray<readonly [string, ToolId, Ceiling | null, ReadonlyArray<readonly [number, number, number, number, number]>]> = [\n"
    );
    for &(model, tool) in CASES {
        let priced: Vec<[u64; 5]> = mixes()
            .iter()
            .filter_map(|tokens| {
                let cost = dearest(model, tool, tokens)?;
                Some([tokens.input, tokens.output, tokens.cache_read, tokens.cache_write, cost])
            })
            .collect();
        cases += &format!(
            "  [{}, {}, {}, {}],\n",
            json(model),
            json(&tool),
            json(&table.ceiling(model, tool)),
            json(&priced)
        );
    }
    cases += "];\n";

    let dir = env::var_os("TOKENTRACKY_CEILINGS_OUT").map_or_else(
        || PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/cloud/src/generated"),
        PathBuf::from,
    );
    fs::create_dir_all(&dir).unwrap();
    fs::write(dir.join("price-ceilings.ts"), out).unwrap();
    fs::write(dir.join("price-ceiling-cases.ts"), cases).unwrap();
}
