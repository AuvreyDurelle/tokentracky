//! Writes `packages/core/src/generated/index.ts` from the Rust types; `TOKENTRACKY_TS_OUT` overrides the directory.
use std::{env, fs, path::PathBuf};
use tokentracky_core::*;
use ts_rs::{Config, TS};

const HEADER: &str = "// Generated by crates/core. Do not edit.\n// Regenerate with `cargo test -p tokentracky-core`; CI checks it with scripts/check-generated-types.sh.\n";

#[test]
fn generates_typescript_types() {
    let cfg = Config::new();
    let ids: Vec<String> = TOOL_IDS
        .iter()
        .map(|tool| serde_json::to_string(tool).unwrap())
        .collect();
    let names: Vec<String> = TOOL_IDS
        .iter()
        .zip(&ids)
        .map(|(tool, id)| {
            format!(
                "{}: {}",
                id.trim_matches('"'),
                serde_json::to_string(tool.name()).unwrap()
            )
        })
        .collect();
    let mut out = format!("{HEADER}\nexport const TOOL_IDS = [{}] as const;\n", ids.join(", "));
    out += &render(ToolId::docs(), ToolId::decl(&cfg));
    out += &format!(
        "export const TOOL_NAMES: Record<ToolId, string> = {{ {} }};\n",
        names.join(", ")
    );
    let badges: Vec<String> = BADGE_IDS
        .iter()
        .map(|badge| serde_json::to_string(badge).unwrap())
        .collect();
    out += &format!("export const BADGE_IDS = [{}] as const;\n", badges.join(", "));
    out += &render(BadgeId::docs(), BadgeId::decl(&cfg));
    for (docs, decl) in [
        (Period::docs(), Period::decl(&cfg)),
        (TokenCounts::docs(), TokenCounts::decl(&cfg)),
        (CostParts::docs(), CostParts::decl(&cfg)),
        (UsageEvent::docs(), UsageEvent::decl(&cfg)),
        (ParseResult::docs(), ParseResult::decl(&cfg)),
        (SourceState::docs(), SourceState::decl(&cfg)),
        (SourceStatus::docs(), SourceStatus::decl(&cfg)),
        (UsageSummary::docs(), UsageSummary::decl(&cfg)),
        (SessionSummary::docs(), SessionSummary::decl(&cfg)),
        (ProjectSummary::docs(), ProjectSummary::decl(&cfg)),
        (PublicProfile::docs(), PublicProfile::decl(&cfg)),
        (LeaderboardResponse::docs(), LeaderboardResponse::decl(&cfg)),
        (LeaderboardNeighbours::docs(), LeaderboardNeighbours::decl(&cfg)),
        (Publication::docs(), Publication::decl(&cfg)),
        (PublicBucket::docs(), PublicBucket::decl(&cfg)),
        (PublicHour::docs(), PublicHour::decl(&cfg)),
        (ProfileStats::docs(), ProfileStats::decl(&cfg)),
        (CommunityStats::docs(), CommunityStats::decl(&cfg)),
        (ExactAggregates::docs(), ExactAggregates::decl(&cfg)),
        (ExactTokenCounts::docs(), ExactTokenCounts::decl(&cfg)),
        (BadgeProgress::docs(), BadgeProgress::decl(&cfg)),
        (AchievementRarity::docs(), AchievementRarity::decl(&cfg)),
        (UsageBreakdownRow::docs(), UsageBreakdownRow::decl(&cfg)),
        (HourBreakdownRow::docs(), HourBreakdownRow::decl(&cfg)),
        (ActivityStats::docs(), ActivityStats::decl(&cfg)),
        (MenuOverview::docs(), MenuOverview::decl(&cfg)),
        (PeriodCosts::docs(), PeriodCosts::decl(&cfg)),
        (MenuBarShows::docs(), MenuBarShows::decl(&cfg)),
        (MenuBarPeriod::docs(), MenuBarPeriod::decl(&cfg)),
        (LocalSettings::docs(), LocalSettings::decl(&cfg)),
    ] {
        out += &render(docs, decl);
    }
    assert!(
        !out.contains("bigint"),
        "a u64 field is missing #[ts(type = \"number\")]"
    );
    let dir = env::var_os("TOKENTRACKY_TS_OUT").map_or_else(
        || PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/core/src/generated"),
        PathBuf::from,
    );
    fs::create_dir_all(&dir).unwrap();
    fs::write(dir.join("index.ts"), out).unwrap();
}

/// `export type X = {` with one field per line; ts-rs emits each declaration on a single line.
fn render(docs: Option<String>, decl: String) -> String {
    let mut out = docs.map(|docs| doc(&docs, "")).unwrap_or_default();
    let Some((head, body)) = decl.split_once(" = { ").filter(|_| decl.ends_with(" };")) else {
        return format!("{out}export {decl}\n");
    };
    out += &format!("export {head} = {{\n");
    for field in split_fields(body.trim_end_matches(" };")) {
        let (comment, field) = match field.trim().strip_prefix("/**").and_then(|rest| rest.split_once("*/")) {
            Some((comment, field)) => (doc(&format!("/**{comment}*/"), "  "), field.trim()),
            None => (String::new(), field.trim()),
        };
        out += &format!("{comment}  {};\n", field.replace(", }", " }"));
    }
    out + "};\n"
}

/// A one-line JSDoc block as `/** text */`.
fn doc(block: &str, indent: &str) -> String {
    let lines: Vec<&str> = block
        .lines()
        .map(|line| line.trim().trim_start_matches("/**").trim_start_matches('*'))
        .collect();
    let text: Vec<&str> = lines
        .iter()
        .map(|line| line.trim_end_matches('/').trim())
        .filter(|line| !line.is_empty())
        .collect();
    format!("{indent}/** {} */\n", text.join(" "))
}

/// Splits an object body at top-level commas, skipping comments and nested types.
fn split_fields(body: &str) -> Vec<&str> {
    let (mut fields, mut depth, mut start, mut comment) = (Vec::new(), 0, 0, false);
    let bytes = body.as_bytes();
    for (i, &c) in bytes.iter().enumerate() {
        match c {
            b'*' if !comment && i > 0 && bytes[i - 1] == b'/' => comment = true,
            b'/' if comment && bytes[i - 1] == b'*' => comment = false,
            _ if comment => {}
            b'{' | b'[' | b'(' | b'<' => depth += 1,
            b'}' | b']' | b')' | b'>' => depth -= 1,
            b',' if depth == 0 => {
                fields.push(&body[start..i]);
                start = i + 1;
            }
            _ => {}
        }
    }
    fields.push(&body[start..]);
    fields.into_iter().filter(|field| !field.trim().is_empty()).collect()
}
